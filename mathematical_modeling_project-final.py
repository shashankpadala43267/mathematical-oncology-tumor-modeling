"""Treatment Intensity and Duration Cell

A parameter sweep compares 900 combinations of treatment duration and drug kill rate. A heatmap visualizes the resulting tumor population at day 100.
"""

kill_rates = np.linspace(0, 0.8, 30)
durations = np.linspace(5, 40, 30)
