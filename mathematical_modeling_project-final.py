"""Treatment vs. No Treatment Cell

A treatment-dependent death term is incorporated into the logistic growth model. Treated and untreated tumor populations are compared to investigate the effects of treatment and subsequent tumor regrowth.
"""

import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp

def simulate_treatment(d, r=0.2, K=1000, N0=10):
    segments = [(0, 20, 0), (20, 40, d), (40, 100, 0)]
    times, sizes = [], []
    current = N0

    for start, end, kill_rate in segments:
        def rhs(t, N):
            return logistic(t, N, r, K) - kill_rate * N

        sol = solve_ivp(
            rhs, (start, end), [current],
            t_eval=np.linspace(start, end, 101),
            rtol=1e-8, atol=1e-10
        )
        if not sol.success:
            raise RuntimeError(sol.message)

        first = 0 if start == 0 else 1
        times.extend(sol.t[first:])
        sizes.extend(sol.y[0, first:])
        current = sol.y[0, -1]

    return np.array(times), np.array(sizes)


for d, label in [(0, "No Treatment"), (0.4, "Treatment (Days 20–40)")]:
    t, N = simulate_treatment(d)
    plt.plot(t, N, label=label)

plt.xlabel("Time (days)")
plt.ylabel("Modeled tumor population (arbitrary units)")
plt.title("Treatment vs. No Treatment")
plt.legend()
plt.grid(True)
plt.show()

