""" Single-Course vs. Intermittent Treatment Cell

A continuous treatment course is compared with two separate treatment periods. Both schedules have the same total treatment duration and drug kill rate, allowing the effects of treatment timing on tumor reduction and regrowth to be investigated.
"""

import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp

def simulate_windows(windows, d=0.4, r=0.2, K=1000, N0=10):
    cuts = {0, 100}
    for start, end in windows:
        cuts.update([start, end])
    cuts = sorted(cuts)

    times, sizes = [], []
    current = N0

    for start, end in zip(cuts, cuts[1:]):
        midpoint = (start + end) / 2
        on_treatment = any(a <= midpoint < b for a, b in windows)
        kill_rate = d if on_treatment else 0

        def rhs(t, N):
            return logistic(t, N, r, K) - kill_rate * N

        sol = solve_ivp(
            rhs, (start, end), [current],
            t_eval=np.linspace(start, end, 101),
            rtol=1e-8, atol=1e-10
        )
        times.extend(sol.t)
        sizes.extend(sol.y[0])
        current = sol.y[0, -1]

    return np.array(times), np.array(sizes)


plans = [
    ("One Course (Days 20–40)", [(20, 40)]),
    ("Two Pulses (20–30, 50–60)", [(20, 30), (50, 60)])
]

for name, windows in plans:
    t, N = simulate_windows(windows)
    plt.plot(t, N, label=name)

    minimum = N[t >= 20].min()
    print(f"{name}: min from day 20 = {minimum:.1f}, day 100 = {N[-1]:.1f}")

plt.xlabel("Time (days)")
plt.ylabel("Modeled tumor population (arbitrary units)")
plt.title("One Treatment Course vs. Two Pulses")
plt.legend()
plt.grid(True)
plt.show()

