"""Logistic and Gompertz Growth Models Cell

Unlike exponential growth, logistic and Gompertz models incorporate limitations on tumor population growth. Both models approach a carrying capacity, but they differ in how growth slows as the tumor population increases.
"""

r, N0, dt = 0.2, 10, 0.5
t = dt * np.arange(61)
sizes = [N0]
for _ in t[1:]:
    size = sizes[-1]
    sizes.append(size + r * size * dt)
plt.plot(t, sizes, label="Euler Steps")
plt.plot(t, N0 * np.exp(r * t), "--", label="Exact Solution")
plt.xlabel("Time (days)")
plt.ylabel("Modeled tumor population (arbitrary units)")
plt.title("Euler's Method vs. Exact Solution")
plt.legend()
plt.grid(True)
plt.show()

def logistic(t, N, r, K):
    return r * N * (1 - N / K)
def gompertz(t, N, r, K):
    return r * N * np.log(K / N)
t_eval = np.linspace(0, 80, 400)
for model, label in [(logistic, "Logistic"), (gompertz, "Gompertz")]:
    sol = solve_ivp(model, (0, 80), [10], args=(0.2, 1000), t_eval=t_eval)
    plt.plot(sol.t, sol.y[0], label=label)
plt.axhline(1000, linestyle="--", color="gray", label="K")
plt.xlabel("Time (days)")
plt.ylabel("Modeled tumor population (arbitrary units)")
plt.title("Logistic vs. Gompertz Growth")
