"""Tumor Drug Resistance Cell

The tumor is divided into drug-sensitive and pre-existing drug-resistant populations that compete for shared resources. This model investigates how differences in treatment sensitivity influence tumor composition and regrowth.
"""

def resistance_model(t, y, treatment):
    S, R = y
    competition = 1 - (S + R) / 1000
    dS = 0.4 if treatment else 0
    dR = 0.02 if treatment else 0

    return [
        0.2 * S * competition - dS * S,
        0.15 * R * competition - dR * R
    ]


current = [9.9, 0.1]
times, populations = [], []

for start, end, on in [(0, 20, False), (20, 60, True), (60, 100, False)]:
    sol = solve_ivp(
        resistance_model, (start, end), current,
        args=(on,), t_eval=np.linspace(start, end, 200),
        rtol=1e-8, atol=1e-10
    )
    if not sol.success:
        raise RuntimeError(sol.message)

    times.append(sol.t)
    populations.append(sol.y)
    current = sol.y[:, -1]

times = np.concatenate(times)
S, R = np.concatenate(populations, axis=1)
total = S + R

plt.figure(figsize=(10, 5))
plt.plot(times, S, label="Sensitive cells")
plt.plot(times, R, label="Resistant cells")
plt.plot(times, total, "--", label="Total tumor")
plt.axvspan(20, 60, alpha=0.15, label="Treatment")
plt.xlabel("Time (days)")
plt.ylabel("Modeled tumor population (arbitrary units)")
plt.title("Tumor Drug Resistance")
plt.legend()
plt.grid(alpha=0.3)
plt.show()

print("Final tumor population:", round(total[-1], 2))
print("Final resistant percentage:", round(100 * R[-1] / total[-1], 2))

